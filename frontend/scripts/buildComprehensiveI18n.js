function augmentDict(dict) {
  const augmented = { ...dict };
  Object.keys(en).forEach(k => {
    const enVal = en[k];
    const transVal = dict[k] || enVal;
    if (enVal && typeof enVal === 'string') {
      augmented[enVal] = transVal;
      augmented[enVal.toLowerCase()] = transVal;
      augmented[enVal.toUpperCase()] = transVal;
      augmented[enVal.trim()] = transVal;
    }
  });

  // Dynamic soil phrases synthesis
  const soilTypes = ['Loamy', 'Black', 'Alluvial', 'Red', 'Clay', 'Sandy'];
  soilTypes.forEach(soil => {
    const soilEn = `${soil} Soil`;
    const soilKey = `${soil.toLowerCase()}Soil`;
    const soilTrans = augmented[soilKey] || augmented[soilEn] || dict[soilKey] || soilEn;
    const sel = augmented['Selected'] || dict['selected'] || 'Selected';
    augmented[`Selected: ${soil} Soil`] = `${sel}: ${soilTrans}`;
    augmented[`SELECTED: ${soil.toUpperCase()} SOIL`] = `${sel.toUpperCase()}: ${soilTrans}`;
    augmented[`selected: ${soil.toLowerCase()} soil`] = `${sel}: ${soilTrans}`;
    augmented[`Selected: ${soil}`] = `${sel}: ${soilTrans}`;
    augmented[`SELECTED: ${soil.toUpperCase()}`] = `${sel.toUpperCase()}: ${soilTrans}`;
  });

  // Black cotton specific
  if (augmented['Black Cotton']) {
    const sel = augmented['Selected'] || dict['selected'] || 'Selected';
    augmented[`Selected: Black Cotton Soil`] = `${sel}: ${augmented['Black Cotton']}`;
    augmented[`SELECTED: BLACK COTTON SOIL`] = `${sel.toUpperCase()}: ${augmented['Black Cotton']}`;
  }

  // Add common aliases
  if (augmented['Risk Analysis']) {
    augmented['Risky Analysis'] = augmented['Risk Analysis'];
    augmented['risky analysis'] = augmented['Risk Analysis'];
  }
  if (augmented['Government Schemes']) {
    augmented['Govt Schemes'] = augmented['Government Schemes'];
    augmented['govt schemes'] = augmented['Government Schemes'];
  }
  if (augmented['Ret.']) {
    augmented['ret.'] = augmented['Ret.'];
    augmented['RET.'] = augmented['Ret.'];
    augmented['Ret'] = augmented['Ret.'];
  }
  if (augmented['Air']) {
    augmented['air'] = augmented['Air'];
    augmented['AIR'] = augmented['Air'];
  }
  if (augmented['Quick Access']) {
    augmented['QUICK ACCESS'] = augmented['Quick Access'];
    augmented['quick access'] = augmented['Quick Access'];
  }
  if (augmented['Search all tools & features...']) {
    augmented['search all tools & features...'] = augmented['Search all tools & features...'];
  }
  return augmented;
}

