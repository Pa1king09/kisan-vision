/**
 * Returns the exact photograph, emoji, and display name for any crop label.
 */
export const getCropData = (cropName) => {
    if (!cropName || typeof cropName !== 'string') {
        return {
            url: '/crops/rice.jpg',
            emoji: '🌱',
            name: cropName || 'Crop'
        };
    }

    const clean = cropName.toLowerCase().trim();

    // 1. Exact match on raw string
    if (CROP_DATABASE[clean]) {
        return CROP_DATABASE[clean];
    }

    // 2. Remove parenthesized text: "Wheat (Gehun)" -> "wheat"
    const withoutParens = clean.replace(/\s*\([^)]*\)/g, '').trim();
    if (CROP_DATABASE[withoutParens]) {
        return CROP_DATABASE[withoutParens];
    }

    // 3. Match against known keys in CROP_DATABASE (longer keys first to prevent false partials)
    const keys = Object.keys(CROP_DATABASE).sort((a, b) => b.length - a.length);
    for (const key of keys) {
        if (clean.startsWith(key) || withoutParens.startsWith(key) || clean.includes(key)) {
            return CROP_DATABASE[key];
        }
    }

    // Fallback if completely unknown
    return {
        url: '/crops/rice.jpg',
        emoji: '🌱',
        name: cropName
    };
};

export const getCropImageUrl = (cropName) => getCropData(cropName).url;
export const getCropEmoji = (cropName) => getCropData(cropName).emoji;
