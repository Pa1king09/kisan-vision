// Get translation for a key, checking ALL_TRANSLATIONS with extensive fallbacks
export const getTranslation = (lang, key) => {
  if (!key || typeof key !== 'string') return key;
  const langDict = ALL_TRANSLATIONS[lang] || ALL_TRANSLATIONS['en'] || {};
  const enDict = ALL_TRANSLATIONS['en'] || {};
  const trimmed = key.trim();
  const lower = trimmed.toLowerCase();

  return langDict[key] ??
         langDict[trimmed] ??
         langDict[lower] ??
         TRANSLATIONS[lang]?.[key] ??
         TRANSLATIONS[lang]?.[trimmed] ??
         enDict[key] ??
         enDict[trimmed] ??
         TRANSLATIONS['en']?.[key] ??
         key;
};

export const LanguageProvider = ({ children }) => {
  const [language, setLanguage] = useState(() => {
    return localStorage.getItem('cv_language') || 'en';
  });
  const [languageSelected, setLanguageSelected] = useState(() => {
    return localStorage.getItem('cv_language_selected') === 'true';
  });

  // Ensure initial language is registered in i18n and document
  useEffect(() => {
    const saved = localStorage.getItem('cv_language') || 'en';
    if (i18n && i18n.changeLanguage && i18n.language !== saved) {
      i18n.changeLanguage(saved);
    }
    if (typeof document !== 'undefined') {
      document.documentElement.lang = saved;
    }
  }, []);

  const selectLanguage = (code) => {
    setLanguage(code);
    setLanguageSelected(true);
    localStorage.setItem('cv_language', code);
    localStorage.setItem('cv_language_selected', 'true');
    localStorage.setItem('i18nextLng', code);

    if (i18n && i18n.changeLanguage) {
      i18n.changeLanguage(code);
    }
    if (typeof document !== 'undefined') {
      document.documentElement.lang = code;
    }
    window.dispatchEvent(new CustomEvent('languagechange', { detail: { language: code } }));
  };

  const resetLanguageSelection = () => {
    setLanguageSelected(false);
    localStorage.removeItem('cv_language_selected');
  };

  const t = (key) => getTranslation(language, key);

  const currentLanguage = LANGUAGES.find(l => l.code === language) || LANGUAGES[0];

  return (
    <LanguageContext.Provider value={{
      language,
      languageSelected,
      currentLanguage,
      selectLanguage,
      resetLanguageSelection,
      t,
      LANGUAGES,
      ALL_TRANSLATIONS,
    }}>
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = () => useContext(LanguageContext);

